<?php

namespace App\Services;

use App\Models\MitelConfiguration;
use Illuminate\Support\Facades\Cache;
use Illuminate\Support\Facades\Http;
use Illuminate\Support\Facades\Log;
use Exception;

/**
 * MCX Open Media v2 integration service.
 *
 * Handles client-credentials auth against the MCX AuthorizationServer,
 * submitting inbound email interactions to the OpenMedia queue, and
 * closing them when a CRM ticket is resolved/closed.
 *
 * Config keys (stored in mitel_configurations table):
 *   MITEL_BASE_URL        — e.g. https://micc.example.com
 *   MITEL_CLIENT_ID       — OAuth2 client_id for this CRM app
 *   MITEL_CLIENT_SECRET   — OAuth2 client_secret
 *   MCX_OM_QUEUE_NUMBER   — Queue Reporting Number for email interactions
 */
class McxOpenMediaService
{
    private const TOKEN_CACHE_KEY   = 'mcx_om_access_token';
    private const TOKEN_BUFFER_SECS = 60;

    private string $baseUrl;
    private string $clientId;
    private string $clientSecret;
    private string $queueName;
    private int    $timeout;

    public function __construct()
    {
        $base = rtrim(MitelConfiguration::getValue('MITEL_BASE_URL', ''), '/');

        $this->baseUrl      = $base;
        $this->clientId     = MitelConfiguration::getValue('MITEL_CLIENT_ID', '');
        $this->clientSecret = MitelConfiguration::getValue('MITEL_CLIENT_SECRET', '');
        $this->queueName    = MitelConfiguration::getValue('MCX_EMAIL_QUEUE_NAME', '');
        $this->timeout      = (int) config('services.mitel.timeout', 30);
    }

    // -------------------------------------------------------------------------
    // Public API
    // -------------------------------------------------------------------------

    /**
     * POST a new email interaction to the OpenMedia queue.
     *
     * @param  string $interactionId  Unique ID generated by the CRM (ticket number or UUID)
     * @param  string $subject        Email subject line
     * @param  string $fromAddress    Sender email address
     * @param  string $bodyText       Plain-text email body (stored as variableData)
     * @return string                 mitelInteractionId returned by MCX
     *
     * @throws Exception on HTTP or MCX-level failure
     */
    public function sendInteraction(
        string $interactionId,
        string $subject,
        string $fromAddress,
        string $bodyText,
        ?string $targetUri = null
    ): string {
        $payload = [
            'queue'        => $this->queueName,
            'subject'      => $subject,
            'from'         => $fromAddress,
            'id'           => $interactionId,
            'variableData' => [
                'emailBody' => $bodyText,
            ],
        ];

        // targetUri tells Mitel Ignite which iframe URL to embed in the agent view
        if ($targetUri) {
            $payload['targetUri']         = $targetUri;
            $payload['targetUriEmbedded'] = true;
        }

        Log::info('[McxOpenMedia] Sending interaction', [
            'id'      => $interactionId,
            'subject' => $subject,
            'from'    => $fromAddress,
            'queue'   => $this->queueName,
        ]);

        $response = $this->post('/miccsdk/api/v1/openmedia', $payload);

        $mitelId = $response['id']
            ?? $response['Id']
            ?? $response['interactionId']
            ?? $response['InteractionId']
            ?? null;

        if (!$mitelId) {
            throw new Exception('MCX did not return an interaction ID. Response: ' . json_encode($response));
        }

        Log::info('[McxOpenMedia] Interaction created', [
            'crm_id'   => $interactionId,
            'mitel_id' => $mitelId,
        ]);

        return (string) $mitelId;
    }

    /**
     * Mark the interaction as Handled (complete) via the OpenMedia v1 API.
     *
     * @param  string      $mitelInteractionId  ID returned by sendInteraction()
     * @param  string|null $reason              Optional close reason (logged only)
     * @return void
     *
     * @throws Exception on HTTP or MCX-level failure
     */
    public function closeInteraction(string $mitelInteractionId, ?string $reason = null): void
    {
        Log::info('[McxOpenMedia] Closing interaction', [
            'mitel_id' => $mitelInteractionId,
            'reason'   => $reason,
        ]);

        $this->put(
            "/miccsdk/api/v1/openmedia/{$mitelInteractionId}",
            ['interactionState' => 'Handled']
        );

        Log::info('[McxOpenMedia] Interaction closed', ['mitel_id' => $mitelInteractionId]);
    }

    /**
     * Get the current conversation state of an interaction.
     * Returns null if the interaction does not exist (404 = handled/removed).
     */
    public function getInteractionState(string $mitelInteractionId): ?string
    {
        $url      = $this->baseUrl . "/miccsdk/api/v1/openmedia/{$mitelInteractionId}";
        $response = Http::timeout($this->timeout)
            ->withToken($this->getToken())
            ->acceptJson()
            ->get($url);

        if ($response->status() === 404) {
            return null; // Interaction handled/removed from Mitel
        }

        if (!$response->successful()) {
            throw new Exception("MCX getInteractionState [{$response->status()}]: " . $response->body());
        }

        $data = $response->json() ?? [];
        return $data['conversationState'] ?? $data['interactionState'] ?? 'Unknown';
    }

    // -------------------------------------------------------------------------
    // Token management
    // -------------------------------------------------------------------------

    /**
     * Return a cached Bearer token, refreshing it if within the buffer window.
     */
    private function getToken(): string
    {
        if (Cache::has(self::TOKEN_CACHE_KEY)) {
            return Cache::get(self::TOKEN_CACHE_KEY);
        }

        return $this->fetchToken();
    }

    /**
     * Perform the client_credentials token request and cache the result.
     */
    private function fetchToken(): string
    {
        $tokenUrl = $this->baseUrl . '/AuthorizationServer/Token';

        Log::info('[McxOpenMedia] Fetching new Bearer token', ['url' => $tokenUrl]);

        $response = Http::timeout($this->timeout)
            ->withHeaders(['Cache-Control' => 'no-cache'])
            ->asForm()
            ->post($tokenUrl, [
                'grant_type'    => 'client_credentials',
                'client_id'     => $this->clientId,
                'client_secret' => $this->clientSecret,
            ]);

        if (!$response->successful()) {
            throw new Exception(
                "MCX token request failed [{$response->status()}]: " . $response->body()
            );
        }

        $data      = $response->json();
        $token     = $data['access_token'] ?? null;
        $expiresIn = (int) ($data['expires_in'] ?? 3600);

        if (!$token) {
            throw new Exception('MCX token response missing access_token: ' . $response->body());
        }

        // Cache the token, shaving off a buffer so we renew before actual expiry
        $ttl = max(30, $expiresIn - self::TOKEN_BUFFER_SECS);
        Cache::put(self::TOKEN_CACHE_KEY, $token, $ttl);

        Log::info('[McxOpenMedia] Token cached', ['expires_in' => $expiresIn, 'cached_ttl' => $ttl]);

        return $token;
    }

    // -------------------------------------------------------------------------
    // HTTP helper
    // -------------------------------------------------------------------------

    /**
     * POST JSON to a MCX endpoint with a Bearer token.
     *
     * Automatically retries once after a 401 by forcing a token refresh.
     */
    private function post(string $path, array $payload, bool $isRetry = false): array
    {
        $url   = $this->baseUrl . $path;
        $token = $this->getToken();

        $response = Http::timeout($this->timeout)
            ->withToken($token)
            ->acceptJson()
            ->post($url, $payload);

        // On 401 refresh token once
        if ($response->status() === 401 && !$isRetry) {
            Cache::forget(self::TOKEN_CACHE_KEY);
            return $this->post($path, $payload, true);
        }

        if (!$response->successful()) {
            throw new Exception(
                "MCX API error [{$response->status()}] on {$path}: " . $response->body()
            );
        }

        return $response->json() ?? [];
    }

    /**
     * PUT JSON to a MCX endpoint with a Bearer token.
     *
     * Automatically retries once after a 401 by forcing a token refresh.
     */
    private function put(string $path, array $payload, bool $isRetry = false): array
    {
        $url   = $this->baseUrl . $path;
        $token = $this->getToken();

        $response = Http::timeout($this->timeout)
            ->withToken($token)
            ->acceptJson()
            ->put($url, $payload);

        if ($response->status() === 401 && !$isRetry) {
            Cache::forget(self::TOKEN_CACHE_KEY);
            return $this->put($path, $payload, true);
        }

        if (!$response->successful()) {
            throw new Exception(
                "MCX API error [{$response->status()}] on PUT {$path}: " . $response->body()
            );
        }

        return $response->json() ?? [];
    }
}
